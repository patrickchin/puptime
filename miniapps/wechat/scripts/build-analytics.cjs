// Copy only the pure analytics used by the miniapp, from the app's source.
// No runtime dependency or second implementation of frequency calculations.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '../../..');
const selections = {
  'src/domain.ts': ['dateKey', 'formatDuration', 'normalizeCustomLabel', 'customActivityKey', 'activityKey', 'sameActivity'],
  'src/analytics.ts': ['windowedEvents', 'percentile', 'activityFrequencyStats', 'activityMonthDate', 'monthlyActivityStats'],
};
let source = '// Generated by miniapps/wechat/scripts/build-analytics.cjs. Edit src/analytics.ts or src/domain.ts.\n';
for (const [file, names] of Object.entries(selections)) {
  const input = fs.readFileSync(path.join(root, file), 'utf8');
  const ast = ts.createSourceFile(file, input, ts.ScriptTarget.Latest, true);
  for (const name of names) {
    const node = ast.statements.find(statement => ts.isFunctionDeclaration(statement) && statement.name?.text === name);
    if (!node) throw new Error(`Missing shared function: ${name}`);
    source += node.getText(ast).replace(/^export /, '') + '\n';
  }
}
source += 'module.exports = { activityFrequencyStats, monthlyActivityStats, formatDuration };\n';
const output = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.CommonJS, removeComments: false } }).outputText;
const destination = path.join(root, 'miniapps/wechat/app/utils/analytics.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('Run node miniapps/wechat/scripts/build-analytics.cjs to refresh shared analytics.');
} else fs.writeFileSync(destination, output);
