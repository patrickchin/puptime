const dictionaries: Record<AppLanguage, Dictionary> = {
  en: english,
  'zh-Hans': simplifiedChinese,
  es: spanish,
};

export type TranslationVariables = Record<string, string | number>;

export function isLanguagePreference(value: string | null): value is LanguagePreference {
  return value !== null && languageChoices.includes(value as LanguagePreference);
}

export function resolveLanguage(
  preference: LanguagePreference,
  deviceLocale = Intl.DateTimeFormat().resolvedOptions().locale,
): AppLanguage {
  if (preference !== 'system') return preference;
  const locale = deviceLocale.toLowerCase();
  if (locale.startsWith('zh')) return 'zh-Hans';
  if (locale.startsWith('es')) return 'es';
  return 'en';
}

export function translate(
  language: AppLanguage,
  key: MessageKey,
  variables: TranslationVariables = {},
): string {
  return dictionaries[language][key].replace(/\{(\w+)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match
  ));
}

